pub fn format(language: UiLanguage, message: Message, value: &str) -> String {
    text(language, message).replace("{action}", value)
}

pub fn format_with_detail(
    language: UiLanguage,
    message: Message,
    action: &str,
    detail: &str,
) -> String {
    text(language, message)
        .replace("{action}", action)
        .replace("{detail}", detail)
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn languages_return_distinct_messages() {
        assert_eq!(text(UiLanguage::English, Message::Settings), "Settings");
        assert_eq!(
            text(UiLanguage::ChineseSimplified, Message::Settings),
            "设置"
        );
    }

    #[test]
    fn formats_dynamic_action_name() {
        assert_eq!(
            format(UiLanguage::English, Message::Processing, "Translate"),
            "Processing Translate…"
        );
    }
}
